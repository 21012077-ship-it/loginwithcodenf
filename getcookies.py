if __name__ == "__main__":
    emails = read_lines_from_file(INPUT_FILENAME)
    proxies = read_lines_from_file(PROXY_FILENAME)

    if not emails:
        print(f"❌ File '{INPUT_FILENAME}' trống hoặc chưa tạo.")
