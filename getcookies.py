def is_netflix_proxy_block_message(message: str | None) -> bool:
    if not message:
        return False
    normalized = " ".join(message.lower().split())
    blocked_markers = [
        "đã xảy ra lỗi",
        "vui lòng thử lại trong vài phút",
        "something went wrong",
        "please try again later",
        "recaptcha",
    ]
    return any(marker in normalized for marker in blocked_markers)

def _extract_netflix_message_pw(page) -> str | None:
    selectors = [
        "div[data-uia='UIMessage-content']",
        "div.ui-message-container",
        "div[role='alert']",
        "div.alert-error",
    ]
    for css in selectors:
        try:
            loc = page.locator(css).first
            if loc.count() > 0:
                return (loc.inner_text(timeout=500) or "").strip()
        except:
            pass
    return None


def first_visible_locator(page, selectors: list[str], *, timeout_ms: int = 15000):
    """Trả về locator đầu tiên thật sự đang hiển thị trong danh sách selector.

    Playwright `.or_().first` lấy phần tử đầu tiên theo DOM, nên nếu trang còn
    giữ một input email ẩn trước input thật thì `wait_for(state="visible")` sẽ
    timeout dù selector đã match đúng. Hàm này duyệt từng phần tử match được và
    chỉ chọn phần tử đang visible.
    """
    deadline = time.time() + (timeout_ms / 1000)
    last_error = None

    while time.time() < deadline:
        for selector in selectors:
            try:
                locators = page.locator(selector)
                for index in range(locators.count()):
                    loc = locators.nth(index)
                    if loc.is_visible(timeout=250):
                        return loc
            except Exception as e:
                last_error = e
        time.sleep(0.25)

    detail = f"; lỗi cuối: {last_error}" if last_error else ""
    raise PWTimeout(f"Không tìm thấy phần tử visible cho selectors: {selectors}{detail}")

def slow_fill_input(locator, value: str, *, delay_ms: int = EMAIL_TYPE_DELAY_MS) -> bool:
    """Xóa ô nhập rồi gõ chậm từng ký tự để tránh website bỏ sót email."""
    expected = value.strip()

    for _ in range(max(1, EMAIL_TYPE_ATTEMPTS)):
        locator.click(force=True)
        locator.press("Control+A")
        locator.press("Backspace")
        locator.type(expected, delay=max(0, delay_ms))
        if POST_EMAIL_TYPE_PAUSE_SECONDS > 0:
            time.sleep(POST_EMAIL_TYPE_PAUSE_SECONDS)
        if locator.input_value(timeout=1000).strip().lower() == expected.lower():
            return True

    return False

def fill_netflix_email(page, email: str) -> bool:
    """Điền email vào mọi biến thể ô email Netflix đang hiển thị."""
