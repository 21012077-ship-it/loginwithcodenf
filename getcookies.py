def _login_once_to_browse(data_package):
    email, proxy_str = data_package

    result = {
        "Email": email,
        "Status": "Failed",
        "Note": "",
        "Profile_Info": "",
        "Cookie_Netscape": "",
        "Proxy_Used": proxy_str if proxy_str else "Direct"
    }

    proxy_config = parse_proxy(proxy_str)

    try:
        with sync_playwright() as p:
            launch_args = {
                "headless": True,
                "channel": "chrome",
                "args": [
                    "--start-maximized",
                    "--disable-blink-features=AutomationControlled",
                    "--disable-infobars",
                    "--no-sandbox"
                ]
            }
            if proxy_config:
                launch_args["proxy"] = proxy_config

            browser = p.chromium.launch(**launch_args)

            context = browser.new_context(
                viewport=None,
                locale="vi-VN",
                user_agent="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/121.0.0.0 Safari/537.36"
            )
            context.add_init_script("Object.defineProperty(navigator, 'webdriver', {get: () => undefined})")

            netflix_page = context.new_page()

            if proxy_str:
                print(f"🌍 {email}: Đang chạy với Proxy {proxy_str}")

            if LOGIN_START_JITTER_SECONDS > 0:
                time.sleep(random.uniform(0, LOGIN_START_JITTER_SECONDS))

            ok, msg = netflix_continue_wait_otp(netflix_page, email)
            if not ok:
                print(f"❌ {email}: {msg}")
                # --- SỬA ĐỔI: NẾU LỖI TIMEOUT THÌ ĐÁNH DẤU LƯU ---
                if "Timeout" in msg or "Target closed" in msg or is_netflix_proxy_block_message(msg):
                    result["Status"] = "ProxyError" # Đặt trạng thái riêng
                    result["Note"] = "Netflix chặn IP/proxy hoặc rate-limit; thử proxy dân cư sạch, giảm luồng, đổi IP rồi chạy lại"
                else:
                    result["Note"] = msg
                # -------------------------------------------------
                browser.close()
                return result

            # Khởi tạo tab lấy mã đăng nhập mới và điền email
            access_page = context.new_page()
            access_info_prepare_search(access_page, email)

            for i in range(MAX_RETRIES):
                print(f"🔄 {email}: Thử code lần {i+1}...")

                if get_and_paste_code_until_browse(netflix_page, access_page):
                    print(f"✅ {email}: ĐÃ VÀO /browse. Đang check profile...")

                    # 1. Check Profile
                    profile_status = check_profiles_status(netflix_page)
                    print(f"🔎 {email} Profiles: {profile_status}")
                    result["Profile_Info"] = profile_status

                    # 2. Check Payment Status
                    final_note = "OK"
                    try:
                        print(f"💳 {email}: Checking payment URL...")
                        netflix_page.goto("https://www.netflix.com/simplemember/retrypayment")
                        time.sleep(3)

                        current_url = netflix_page.url
                        if "retrypayment" in current_url:
                            final_note = "Tài khoản hết hạn"
                            print(f"⚠️ {email}: Hết hạn thanh toán.")
                        else:
                            final_note = "OK"

                    except Exception as e:
                        print(f"⚠️ {email}: Lỗi check payment - {e}")
                        final_note = "Lỗi check payment"

                    cookies_json = context.cookies()
                    netscape_str = convert_to_netscape_format(cookies_json)
                    save_txt_backup(email, netscape_str)

                    result["Status"] = "Success"
                    result["Note"] = final_note
                    result["Cookie_Netscape"] = netscape_str

                    time.sleep(1)
                    browser.close()
                    return result

                time.sleep(5)

            print(f"❌ {email}: Hết số lần thử code.")
            result["Note"] = "Max retries reached"
            browser.close()
            return result

    except Exception as e:
        print(f"❌ {email}: Lỗi - {e}")
        # Nếu lỗi hệ thống lớn mà có timeout cũng lưu luôn
        if "Timeout" in str(e):
             result["Status"] = "ProxyError"
             result["Note"] = "Netflix chặn IP/proxy hoặc proxy timeout; kiểm tra lại proxy"
        else:
             result["Note"] = str(e)
        return result

