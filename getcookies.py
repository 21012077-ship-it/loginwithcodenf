def check_profiles_status(page):
    try:
        try:
            page.wait_for_selector("ul.choose-profile", timeout=5000)
        except:
            return "Không tìm thấy danh sách profile"

        profiles = page.locator("li.profile").all()
        if not profiles:
            return "Không có profile nào"

        open_profiles = []
        locked_count = 0

        for p in profiles:
            try:
                name = p.locator(".profile-name").inner_text()
                if p.locator(".svg-icon-profile-lock").is_visible():
                    locked_count += 1
                else:
                    open_profiles.append(name)
            except:
                continue

        if open_profiles:
            return f"MỞ: {', '.join(open_profiles)} | KHÓA: {locked_count}"
        elif locked_count > 0:
            return f"FULL KHÓA ({locked_count} profiles)"
        else:
            return "Check lại (Không xác định trạng thái)"

    except Exception as e:
        return f"Lỗi check profile: {str(e)}"

