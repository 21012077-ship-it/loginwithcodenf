    print("---------------------------------------------------------------")

    all_results = []

    pool = Pool(processes=MAX_CONCURRENT_PROCESSES)
    try:
        async_result = pool.map_async(worker_process, tasks)
        while not async_result.ready():
            time.sleep(1)
        all_results = async_result.get()

    except KeyboardInterrupt:
        print("\n🛑 Đã nhận lệnh dừng (Ctrl+C). Đang hủy các tiến trình con...")
        pool.terminate()
        pool.join()
        print("✅ Đã dừng chương trình an toàn.")
        raise SystemExit(0)
    except Exception as e:
        print(f"❌ Lỗi hệ thống: {e}")
        pool.terminate()
    finally:
        pool.close()
        try:
            pool.join()
        except:
            pass

    print("---------------------------------------------------------------")
    print("💾 Đang xử lý và lưu file Excel...")

    try:
        if all_results:
            df = pd.DataFrame(all_results)
            if "Status" in df.columns:
                # --- SỬA ĐỔI: LỌC CẢ SUCCESS VÀ PROXYERROR ---
                # Lấy những dòng Success HOẶC ProxyError
                df_success = df[df["Status"].isin(["Success", "ProxyError"])]

                cols_needed = ["Email", "Status", "Note", "Profile_Info", "Proxy_Used", "Cookie_Netscape"]
                # Lọc cột nếu tồn tại
                final_cols = [c for c in cols_needed if c in df_success.columns]

                if not df_success.empty:
                    # Sắp xếp lại cột theo thứ tự cols_needed
                    df_success = df_success[final_cols]

                    thoi_gian = datetime.now().strftime("%Y%m%d_%H%M%S")
                    dynamic_filename = f"Netflix_Accounts_{thoi_gian}.xlsx"
                    df_success.to_excel(dynamic_filename, index=False)
                    print(f"✅ Đã xuất {len(df_success)} tài khoản (bao gồm lỗi proxy) ra file: {dynamic_filename}")
                else:
                    print("⚠️ Không có tài khoản nào cần lưu.")
            else:
                print("⚠️ Dữ liệu trả về thiếu cột Status.")
        else:
            print("⚠️ Không có dữ liệu trả về.")
    except Exception as e:
        print(f"❌ Lỗi ghi file Excel: {e}")
